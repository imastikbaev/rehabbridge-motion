import { titles, type Exercise } from "./movement";

const steps: Record<Exercise, readonly string[]> = {
  bend: [
    "Исходное: кисть ниже плеч, локоть ближе к корпусу. Камера должна различать плечо, локоть и кисть.",
    "Движение: сгибание локтя до согласованной отметки. Для распознавания удерживайте её не менее 0,5 секунды.",
    "Зачёт: возврат в исходное положение и задержка не менее 0,35 секунды. Только затем изменится счётчик.",
  ],
  reach: [
    "Исходное: кисть ближе к корпусу и ниже плеч. Выбранная рука целиком помещается в кадре.",
    "Движение: отведение всей руки в согласованном диапазоне. Камера учитывает положение кисти, локтя и сгибание руки.",
    "Зачёт: после удержания отметки не менее 0,5 секунды — возврат кисти к корпусу и задержка не менее 0,35 секунды.",
  ],
  open: [
    "Исходное: кисть видна в кадре, камера различает не более одного раскрытого пальца из четырёх. Большой палец отдельно не оценивается.",
    "Движение: камера должна увидеть четыре раскрытых пальца не менее 0,5 секунды. Не приближайте кисть так, чтобы она вышла из кадра.",
    "Зачёт: возврат пальцев в исходное положение не менее чем на 0,35 секунды. Исчезновение кисти не считается возвратом.",
  ],
};

export function ExerciseGuide({
  exercise,
  expanded = false,
}: {
  exercise: Exercise;
  expanded?: boolean;
}) {
  const content = (
    <>
      <ol>
        {steps[exercise].map((text) => (
          <li key={text}>{text}</li>
        ))}
      </ol>
      <p>
        Это условия распознавания прототипа. Если они не подходят назначенному
        движению, остановите задание — не увеличивайте усилие ради счётчика.
      </p>
    </>
  );
  return expanded ? (
    <section
      className="exercise-guide"
      aria-label={`Подготовка: ${titles[exercise]}`}
    >
      <h3>Далее: {titles[exercise]}</h3>
      {content}
    </section>
  ) : (
    <details className="exercise-guide">
      <summary>Как засчитывается: {titles[exercise]}</summary>
      {content}
    </details>
  );
}
